/* Deterministic asset export: user-selected local processing preserves source art. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),sharp=require('sharp');
const root=path.resolve(__dirname,'..'),EXPORT_CONFIG={farSigma:1.2,foregroundSigma:1.1,quality:88};
const slugs=['campos-de-cinza','bosque-profanado','criptas-afogadas','fortaleza-de-ferro','fendas-infernais','trono-do-crepusculo'];
(async()=>{
 const art={export:EXPORT_CONFIG,far:{},foreground:{},contacts:{}},exports=[];
 fs.mkdirSync(path.join(root,'assets/backgrounds/depth'),{recursive:true});
 for(let z=0;z<slugs.length;z++){
  const slug=slugs[z],entry={blur:EXPORT_CONFIG.farSigma};
  for(const boss of [false,true]){
   const source=`assets/backgrounds/fast/${slug}${boss?'-boss':''}.webp`,file=`assets/backgrounds/depth/${slug}${boss?'-boss':''}-far.webp`;
   await sharp(path.join(root,source)).blur(EXPORT_CONFIG.farSigma).webp({quality:EXPORT_CONFIG.quality}).toFile(path.join(root,file));
   entry[boss?'bossSrc':'src']=file;exports.push({asset:file,source,bakedBlur:EXPORT_CONFIG.farSigma});
  }art.far[slug]=entry;
 }
 const foreground='assets/backgrounds/depth/campos-de-cinza-foreground-soft.webp',source='assets/backgrounds/layers/campos-de-cinza-foreground.png';
 await sharp(path.join(root,source)).blur(EXPORT_CONFIG.foregroundSigma).webp({quality:90,alphaQuality:100}).toFile(path.join(root,foreground));
 art.foreground[0]={src:foreground,blur:EXPORT_CONFIG.foregroundSigma};exports.push({asset:foreground,source,bakedBlur:EXPORT_CONFIG.foregroundSigma});
 const roster=JSON.parse(fs.readFileSync(path.join(root,'CREATURES.json'),'utf8'));
 for(const file of ['assets/hero/fast/errante.webp',...roster.map(x=>x.asset)]){
  const {data,info}=await sharp(path.join(root,file)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  let l=info.width,t=info.height,r=0,b=0;
  for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>32){l=Math.min(l,x);r=Math.max(r,x+1);t=Math.min(t,y);b=Math.max(b,y+1);}
  let fl=info.width,fr=0;const contactTop=Math.max(t,Math.floor(b-(b-t)*.065));
  for(let y=contactTop;y<b;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>32){fl=Math.min(fl,x);fr=Math.max(fr,x+1);}
  const round=n=>Math.round(n*1e6)/1e6;
  art.contacts[file]={ink:[l/info.width,t/info.height,r/info.width,b/info.height].map(round),foot:[fl/info.width,fr/info.width,b/info.height].map(round)};
 }
 fs.writeFileSync(path.join(root,'round4-art.js'),'/* Generated by tools/build-round4.cjs; source artwork is preserved. */\nwindow.HELLWARD_ROUND4_ART='+JSON.stringify(art)+';\n');
 const auditPath=path.join(root,'docs/sprite-review.json'),audit=JSON.parse(fs.readFileSync(auditPath,'utf8'));
 const names=new Set(exports.map(x=>x.asset));audit.otherRaster=audit.otherRaster.filter(x=>!names.has(x.asset));
 for(const entry of exports)audit.otherRaster.push({...entry,action:'derived-depth-export',method:'local Sharp blur baked before runtime'});
 fs.writeFileSync(auditPath,JSON.stringify(audit,null,2)+'\n');
 console.log('Built 13 baked depth assets and 43 contact silhouettes; original artwork unchanged');
})().catch(e=>{console.error(e);process.exitCode=1;});
